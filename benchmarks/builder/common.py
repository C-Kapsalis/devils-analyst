"""Shared writer for the Devil's Analyst benchmark cases.

Each case script in cases/ simulates its data with a fixed seed, computes the
ground truth in code, asserts that the naive answer differs from it, and calls
write_case(). That writes:

  benchmarks/cases/<name>/{case.yaml, prompt.md, scaffold.sh, graders/*.md}

in the format `claude plugin eval` reads. The fixture data lives only in each
case's scaffold.sh (a heredoc per file); fixture() reads it back. Rebuild
every case (stdlib only):

  python3 benchmarks/builder/build_all.py

Five cases (cac-two-facts, email-mix, ga4-users, gsc-position, roas-stacking)
were written by hand and have no script here; the builder never touches them.
"""

from __future__ import annotations

import csv
import io
import re
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
CASES = REPO / "benchmarks" / "cases"
EOF_MARK = "DEVILS_ANALYST_EOF"

REPORT_LINE = "Save report.md in the current working directory, not inside resources/."


def to_csv(header: list[str], rows: list[list]) -> str:
    """CSV text with a trailing newline; floats printed without noise."""
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(header)
    for r in rows:
        w.writerow([_fmt(v) for v in r])
    return buf.getvalue()


def _fmt(v):
    if isinstance(v, float):
        return f"{v:.6f}".rstrip("0").rstrip(".") if v != int(v) else str(int(v))
    return "" if v is None else v


def write_case(
    name: str,
    files: dict[str, str],
    prompt: str,
    graders: list[tuple[str, int, str]],
    *,
    output: str = "report.md",
    runs: int = 3,
    evals_root: Path | None = None,
    skill_match: str = r'"skill"\s*:\s*"devils-analyst:[\w-]+"',
) -> None:
    """files: {"resources/x.csv": text}. graders: (slug, weight, body) judged on `output`.

    evals_root: where the case directory goes (default benchmarks/cases).
    skill_match: regex the skill-fired grader matches against the Skill tool input.
    """
    assert all(k.startswith("resources/") for k in files), "fixtures live in resources/"
    case = (evals_root or CASES) / name
    if case.exists():
        shutil.rmtree(case)
    (case / "graders").mkdir(parents=True)

    (case / "case.yaml").write_text(
        f'schema_version: "1.1"\nname: {name}\nruns: {runs}\n'
        "context:\n  scaffold_script: scaffold.sh\n"
    )

    save_line = REPORT_LINE if output == "report.md" else (
        f"Save {output} in the current working directory, not inside resources/."
    )
    (case / "prompt.md").write_text(
        "---\nmax_turns: 40\ntimeout_seconds: 900\n"
        "allowed_tools: [Read, Glob, Grep, Skill, Write]\n---\n\n"
        f"{prompt.strip()}\n\n{save_line}\n"
    )

    lines = [
        "#!/usr/bin/env bash",
        "# Writes this case's fixture data into the run's workspace (both arms see the same files).",
        "# Generated by benchmarks/builder; edit the case script there, not this file.",
        "set -euo pipefail",
        "mkdir -p resources",
    ]
    for path, text in files.items():
        assert EOF_MARK not in text
        lines += [f"cat > {path} <<'{EOF_MARK}'", text.rstrip("\n"), EOF_MARK]
    scaffold = case / "scaffold.sh"
    scaffold.write_text("\n".join(lines) + "\n")
    scaffold.chmod(0o755)

    (case / "graders" / "skill-fired.md").write_text(
        "---\ntype: tool_used\ntool: Skill\n"
        f"input_match: '{skill_match}'\n---\n"
    )
    for slug, weight, body in graders:
        (case / "graders" / f"{slug}.md").write_text(
            f"---\ntype: llm\nweight: {weight}\nfocus: {{ source: file, path: {output} }}\n---\n\n"
            f"{body.strip()}\n"
        )


def fixture(case: str, path: str) -> str:
    """The text of one fixture file, read back from an existing case's scaffold.sh."""
    text = (CASES / case / "scaffold.sh").read_text()
    m = re.search(rf"cat > {re.escape(path)} <<'{EOF_MARK}'\n(.*?)\n{EOF_MARK}\n", text, re.S)
    if not m:
        raise FileNotFoundError(f"{path} not in {case}/scaffold.sh")
    return m.group(1) + "\n"
