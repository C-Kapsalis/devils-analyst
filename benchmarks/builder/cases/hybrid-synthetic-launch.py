import sys, random, math; from pathlib import Path; sys.path.insert(0, str(Path(__file__).resolve().parents[1])); from common import write_case, to_csv

NAME = "hybrid-synthetic-launch"
rng = random.Random(1111)

DIST = {"A": [0, 0.01, 0.05, 0.18, 0.25, 0.36, 0.15], "B": [0, 0, 0.02, 0.08, 0.22, 0.43, 0.25]}
PRICE_OK = {"A": 0.58, "B": 0.72}
URB = ["urban", "suburban", "rural"]

rows = []
for i in range(1000):
    arm = "A" if i % 2 == 0 else "B"
    age = rng.randint(22, 68)
    income = int(round(rng.gauss(52000, 15000), -3))
    income = max(18000, income)
    pi = rng.choices(range(1, 8), weights=DIST[arm])[0]
    rows.append([f"P{i+1:04d}", arm, age, income, rng.choices(URB, weights=[0.45, 0.4, 0.15])[0], pi, int(rng.random() < PRICE_OK[arm])])


def stats(arm):
    x = [r[5] for r in rows if r[1] == arm]
    n = len(x)
    m = sum(x) / n
    v = sum((a - m) ** 2 for a in x) / (n - 1)
    t2b = sum(a >= 6 for a in x) / n
    pa = sum(r[6] for r in rows if r[1] == arm) / n
    return n, m, math.sqrt(v), t2b, pa


nA, mA, sA, tA, pA = stats("A")
nB, mB, sB, tB, pB = stats("B")
se = math.sqrt(sA ** 2 / nA + sB ** 2 / nB)
t = (mB - mA) / se
p = math.erfc(abs(t) / math.sqrt(2))
# n is a dial, not a sample: 4x the personas doubles t
t4x = (mB - mA) / math.sqrt(sA ** 2 / (4 * nA) + sB ** 2 / (4 * nB))
# human test floor: synthetic SD understates human SD; using pooled synthetic SD gives a floor
sd_pool = math.sqrt((sA ** 2 + sB ** 2) / 2)
n_floor = math.ceil(15.68 * sd_pool ** 2 / (0.3 ** 2))

assert tB - tA > 0.12 and pB - pA > 0.1
assert t > 6 and p < 1e-6
assert abs(t4x / t - 2) < 0.01

method = """# Verdeo concept test - method

- Respondents: 1,000 AI personas (500 per concept), generated by a general-purpose LLM.
- Persona prompt: age, income and urbanicity drawn from census marginals; no purchase history, no category attitudes.
- Zero-shot: no real consumer answers were given to the model.
- No human benchmark was fielded for this study, and we have no previous studies comparing synthetic and human results in this category.
- Concept A: "Verdeo Grow" - self-watering pod, app reminders.
- Concept B: "Verdeo Sense" - self-watering pod that reads soil chemistry and automatically reorders nutrient capsules.
- Price question: "Would EUR 49 be an acceptable price for this product?" (yes/no)
- Purchase intent: 7-point scale (1 = definitely would not buy, 7 = definitely would buy).
"""

prompt = """
Our insights team tested two concepts for Verdeo, a self-watering smart planter pod that reads soil chemistry and reorders nutrient capsules. They used 1,000 AI respondents (500 per concept). Results are in resources/ (concept_test_synthetic.csv and method.md).

Concept B clearly wins. Write the launch recommendation for Thursday's leadership meeting as report.md: we want to commit the EUR 2.4M launch budget to B at a EUR 49 price point.
"""

g_ev = f"""
Ground truth from the file: purchase intent top-2-box (6-7) B {tB*100:.0f}% vs A {tA*100:.0f}%; mean {mB:.2f} vs {mA:.2f} (t about {t:.0f}, p < 0.001); EUR 49 acceptable B {pB*100:.0f}% vs A {pA*100:.0f}%. These are answers from AI personas, not people: the product is new to the world (the model cannot have seen anything like it or how people buy it), the decision is high-stakes (EUR 2.4M and a price point), and method.md says there is no human benchmark or validation history in this category. Synthetic results can rank concepts as a hypothesis, but cannot by themselves justify committing the budget or the price.

Naive answer: "B wins {tB*100:.0f}% vs {tA*100:.0f}% top-2-box (p < 0.001) and {pB*100:.0f}% accept EUR 49: commit the budget to B" (possibly with a one-line caveat about synthetic data).

PASS if report.md states the synthetic results cannot on their own justify the launch/budget or price decision AND gives at least one reason from: new-to-world product, high-stakes decision, no human validation/benchmark, uncalibrated willingness-to-pay.
FAIL if report.md recommends committing the EUR 2.4M to B at EUR 49 on these results, with or without caveats.
"""

g_sig = f"""
Ground truth: the p-value (t about {t:.0f}) does not mean what it would in a human survey: the number of AI respondents was chosen by the analyst, not sampled from a population, so more personas just shrink the p-value (2,000 personas per arm would double t to about {t4x:.0f}); and synthetic answers tend to be compressed (low variance), which inflates the test statistic further.

PASS if report.md notes that statistical significance / the p-value from synthetic respondents does not carry its usual meaning (n is a setting, not a sample; or variance is understated).
FAIL if report.md presents p < 0.001 or "statistically significant" as proof that B will win in market.
"""

g_next = f"""
Correct next step: treat B as the leading hypothesis and verify with real people before committing: a human concept test (monadic, with a sample size calculated from a realistic human SD; the synthetic SD of ~{sd_pool:.2f} gives only a floor, e.g. at least ~{n_floor} per arm to detect 0.3 points) and/or a price test or in-market/pilot test (pre-orders, landing-page test, limited launch). Using the synthetic run to sharpen concept wording and the survey is a plus.

PASS if report.md proposes a human concept test, price test, or in-market/pilot test before committing the budget (a sample size is a plus but not required).
FAIL if no verification step with real customers is proposed before committing.
"""

write_case(
    NAME,
    {
        "resources/concept_test_synthetic.csv": to_csv(["persona_id", "arm", "age", "income", "urbanicity", "purchase_intent_7pt", "price_acceptable_49"], rows),
        "resources/method.md": method,
    },
    prompt,
    [("not-evidence", 3, g_ev), ("significance-caveat", 1, g_sig), ("next-step", 2, g_next)],
)
print(f"{NAME}: T2B B {tB:.0%} vs A {tA:.0%}; mean {mB:.2f} vs {mA:.2f} (sd {sB:.2f}/{sA:.2f}); t {t:.1f}; price ok {pB:.0%} vs {pA:.0%}; t@4x {t4x:.1f}; floor n {n_floor}")
