import sys, random, math; from pathlib import Path; sys.path.insert(0, str(Path(__file__).resolve().parents[1])); from common import write_case, to_csv

NAME = "hybrid-theme-pooling"
rng = random.Random(1515)

THEMES = ["delivery_delays", "price_vs_supermarket", "packaging_waste", "recipe_repetition", "ai_meal_planning_app", "portion_size", "customer_service"]
HUMAN = {"delivery_delays": 6, "price_vs_supermarket": 5, "packaging_waste": 4, "recipe_repetition": 3, "ai_meal_planning_app": 0, "portion_size": 2, "customer_service": 1}
SYNTH = {"delivery_delays": 2, "price_vs_supermarket": 10, "packaging_waste": 6, "recipe_repetition": 10, "ai_meal_planning_app": 17, "portion_size": 3, "customer_service": 1}


def build(n, counts, prefix):
    flags = {t: [1] * c + [0] * (n - c) for t, c in counts.items()}
    for v in flags.values():
        rng.shuffle(v)
    return [[f"{prefix}{i+1:02d}"] + [flags[t][i] for t in THEMES] for i in range(n)]


human = build(8, HUMAN, "INT-H")
synth = build(20, SYNTH, "INT-S")

hc = {t: sum(r[1 + j] for r in human) for j, t in enumerate(THEMES)}
sc = {t: sum(r[1 + j] for r in synth) for j, t in enumerate(THEMES)}
pooled = {t: hc[t] + sc[t] for t in THEMES}
pooled_rank = sorted(THEMES, key=lambda t: -pooled[t])
human_rank = sorted(THEMES, key=lambda t: -hc[t])
both = [t for t in THEMES if hc[t] / 8 >= 0.3 and sc[t] / 20 >= 0.3]

assert hc == HUMAN and sc == SYNTH
assert pooled_rank[0] == "ai_meal_planning_app" and human_rank[0] == "delivery_delays"
assert pooled_rank.index("delivery_delays") >= 4 and hc["ai_meal_planning_app"] == 0
assert set(both) == {"price_vs_supermarket", "packaging_waste", "recipe_repetition"}

method = """# Interview method

- Human interviews: 8 current FreshCrate subscribers, 45-minute video calls with a moderator, recruited from the customer list (September 2026). Coded by the research team.
- AI interviews: 20 interviews generated by an LLM playing customer personas (demographics + plan type), same discussion guide, no human moderator, no real customer transcripts given to the model. Coded with the same codebook.
- Codebook: one flag per theme if the interview mentions it (1 = mentioned).
"""

prompt = """
We did 8 customer interviews for FreshCrate and topped them up with 20 AI interviews to save time. Theme codes are in resources/ (themes_human.csv, themes_synthetic.csv, method.md).

Write the insights summary for the brand team as report.md: what are customers telling us, ranked by how many interviews mention each theme.
"""

pooled_txt = ", ".join(f"{t} {pooled[t]}/28" for t in pooled_rank)
human_txt = ", ".join(f"{t} {hc[t]}/8" for t in human_rank)
synth_txt = ", ".join(f"{t} {sc[t]}/20" for t in sorted(THEMES, key=lambda t: -sc[t]))

g_pool = f"""
Ground truth: the two sources must be counted separately, because only the 8 human interviews are customers speaking. Human (8): {human_txt}. Synthetic (20): {synth_txt}. "ai_meal_planning_app" appears in 0 of 8 real interviews; it is something the AI personas produced, not something customers said.

Naive answer: pooling all 28 interviews: {pooled_txt}, which ranks "AI meal planning app" as the top customer theme and pushes delivery delays to fifth.

PASS if report.md keeps human and synthetic counts separate (or clearly labels the source of each theme's count) AND does not present AI meal planning as something customers told us.
FAIL if report.md's top-ranked customer theme is AI meal planning, or presents counts pooled over 28 interviews without source labels.
"""

g_deliv = f"""
Ground truth: delivery delays are the strongest real-customer signal: {hc['delivery_delays']} of 8 human interviews (the top human theme), though only {sc['delivery_delays']} of 20 AI interviews mention them.

PASS if report.md reports delivery delays as the leading (or a top-two) theme among real customers.
FAIL if delivery delays are ranked low (e.g. 5th of {len(THEMES)} as in the pooled count), described as minor, or omitted.
"""

g_hyp = f"""
Ground truth: themes found in both sources ({', '.join(both)}) can be reported with more confidence; human-only themes (delivery delays) are real signals the synthetic run missed; the synthetic-only theme (AI meal planning, {sc['ai_meal_planning_app']}/20 synthetic, 0/8 human) is at most a hypothesis to test with real customers.

PASS if report.md labels AI meal planning (the synthetic-only theme) as a hypothesis / unvalidated / to be tested with real customers, or excludes it from the customer findings for that reason.
FAIL if AI meal planning is presented as a validated customer need.
"""

write_case(
    NAME,
    {
        "resources/themes_human.csv": to_csv(["interview_id"] + THEMES, human),
        "resources/themes_synthetic.csv": to_csv(["interview_id"] + THEMES, synth),
        "resources/method.md": method,
    },
    prompt,
    [("no-pooling", 3, g_pool), ("delivery-signal", 2, g_deliv), ("hypothesis-label", 1, g_hyp)],
)
print(f"{NAME}: pooled top {pooled_rank[0]} ({pooled[pooled_rank[0]]}/28), delivery pooled rank {pooled_rank.index('delivery_delays')+1}; human top {human_rank[0]} ({hc[human_rank[0]]}/8)")
